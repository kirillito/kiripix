"""A Prop's states in the export (ticket 0260, spec §9): one scene with a Node2D per state, only the default shown, and
the states' IDs frozen in the Manifest."""

import json
import os
import re
import subprocess
from pathlib import Path

import pytest
from conftest import Kiripix
from test_export import godot_project, node, set_target
from test_export_prop import FOLDER, MANIFEST, ORIGIN, POLYGON, RES, SCENE, exportable_prop, manifest, scene
from test_prop import PROP, built_prop
from test_prop_state_stages import CHAIN, a_state_source, decision, import_state
from test_prop_states import declare

TOPPLED = [[1, 3], [10, 3], [10, 5]]
TOPPLED_ORIGIN = [5, 5]


def child(text: str, name: str, parent: str) -> str:
    """The section of the node `name` whose parent path is `parent` (`node` finds the first of that name)."""
    found = re.search(rf'^\[node name="{re.escape(name)}"[^\n]* parent="{re.escape(parent)}"\]\n(?:[^\[\n][^\n]*\n)*',
                      text, re.MULTILINE)
    assert found, f"no node {name} under {parent} in:\n{text}"
    return found.group(0)


def two_states(project: Kiripix) -> Path:
    """A Prop with a default and a `toppled` state of another size, every Stage built, and a Godot project to export to."""
    folder = built_prop(project)
    declare(project, "toppled", 12, 6)
    import_state(project, "toppled", a_state_source(12, 6))
    for stage in CHAIN:
        project.json("run", PROP, stage)
    project.json("decide", PROP, "footprint", "--decision", decision(None, POLYGON, ORIGIN))
    project.json("decide", PROP, "footprint", "--decision", decision("toppled", TOPPLED, TOPPLED_ORIGIN))
    godot_project(project)
    set_target(project)
    project.json("run", PROP)
    return folder


def test_a_prop_with_two_states_exports_one_scene_with_two_state_nodes_the_second_hidden(project: Kiripix) -> None:
    folder = two_states(project)

    data = project.json("export", PROP)["data"]

    assert sorted(data["written"]) == [f"{RES}/bench.tscn", f"{RES}/sprite.png", f"{RES}/states/toppled.png"]
    text = scene(project)
    assert text.startswith("; generated by kiripix, do not edit\n") and "\r" not in text
    assert 'metadata/kiripix_id = "prop.bench"' in node(text, "bench")
    shown, hidden = node(text, "default", "."), node(text, "toppled", ".")
    assert "visible = false" not in shown and "visible = false" in hidden
    for found, state in ((shown, "default"), (hidden, "toppled")):
        assert 'metadata/kiripix_type = "prop_state"' in found and f'metadata/kiripix_state = "{state}"' in found
        assert 'metadata/kiripix_id = "prop.bench"' in found
    assert "offset = Vector2(-3, -7)" in child(text, "Sprite", "default")
    assert "offset = Vector2(-5, -5)" in child(text, "Sprite", "toppled")
    assert f'path="{RES}/states/toppled.png" id="sprite_toppled"' in text
    assert 'texture = ExtResource("sprite_toppled")' in child(text, "Sprite", "toppled")
    assert "collision_layer = 1" in child(text, "Footprint", "toppled")
    assert "disabled" not in child(text, "polygon_0", "default/Footprint")
    toppled = child(text, "polygon_0", "toppled/Footprint")
    assert "disabled = true" in toppled and "polygon = PackedVector2Array(-4, -2, 5, -2, 5, 0)" in toppled
    assert (project.cwd / FOLDER / "states" / "toppled.png").read_bytes() == (
        folder / "out" / "export" / "states" / "toppled.png").read_bytes()
    prop = json.loads((folder / "out" / "export" / "prop.json").read_text("utf-8"))
    assert prop["schema_version"] == 2 and prop["default"] == "default"
    assert prop["origin"] == ORIGIN and prop["size"] == [8, 8]
    assert prop["states"] == [{"id": "toppled", "file": "states/toppled.png", "size": [12, 6], "origin": TOPPLED_ORIGIN,
                               "collision": prop["states"][0]["collision"]}]
    assert prop["states"][0]["collision"] and len(prop["states"][0]["collision"][0]) == 3
    assert sorted(manifest(project)["files"]) == [f"{RES}/bench.tscn", f"{RES}/sprite.png", f"{RES}/states/toppled.png"]


def test_the_state_ids_are_frozen_in_the_manifest_and_the_scene_is_stable(project: Kiripix) -> None:
    two_states(project)
    project.json("export", PROP)
    before = (project.cwd / SCENE).read_bytes()

    project.json("run", PROP, "export", "--force")
    data = project.json("export", PROP)["data"]

    assert manifest(project)["ids"]["states"] == ["default", "toppled"]
    assert (project.cwd / SCENE).read_bytes() == before and data["written"] == []
    assert not [f for f in project.json("check", PROP)["findings"] if f["code"] == "export.id_frozen"]


def test_an_empty_state_footprint_has_no_body_in_that_node(project: Kiripix) -> None:
    two_states(project)
    project.json("decide", PROP, "footprint", "--decision", decision("toppled", [], TOPPLED_ORIGIN))
    project.json("run", PROP)

    project.json("export", PROP)

    text = scene(project)
    assert "toppled/Footprint" not in text and "default/Footprint" in text


def test_a_prop_with_no_states_has_no_state_nodes_and_no_state_ids(project: Kiripix) -> None:
    exportable_prop(project)

    project.json("export", PROP)

    text = scene(project)
    assert "prop_state" not in text and 'parent="."' in text and "states" not in manifest(project)["ids"]
    prop = json.loads((project.cwd / "assets/prop/bench/out/export/prop.json").read_text("utf-8"))
    assert "states" not in prop and "default" not in prop
    assert not (project.cwd / FOLDER / "states").exists() and (project.cwd / MANIFEST).is_file()


PROBE = """extends SceneTree

func _hits(root: Node, point: Vector2) -> int:
	var query := PhysicsPointQueryParameters2D.new()
	query.position = point
	query.collision_mask = 1
	return root.get_world_2d().direct_space_state.intersect_point(query).size()

func _init() -> void:
	var root: Node2D = load("res://kiripix/prop/bench/bench.tscn").instantiate()
	get_root().add_child(root)
	await physics_frame
	await physics_frame
	var toppled: Node2D = root.get_node("toppled")
	var point := Vector2(4, -1.5)
	var before := _hits(root, point)
	var was_visible := toppled.visible
	toppled.visible = true
	for polygon in toppled.get_node("Footprint").get_children():
		polygon.disabled = false
	await physics_frame
	await physics_frame
	print("PROBE ", JSON.stringify([before, was_visible, _hits(root, point), root.get_node("default").visible]))
	quit()
"""


@pytest.mark.godot
def test_godot_shows_the_second_state_and_its_polygons_give_its_collision(project: Kiripix) -> None:
    """Marked: real Godot 4.7 opens the scene; the hidden state has no collision until it is shown and enabled."""
    two_states(project)
    project.json("export", PROP)
    game = project.cwd / "game"
    (game / "probe.gd").write_text(PROBE, "utf-8")
    godot = os.environ["KIRIPIX_GODOT"]

    subprocess.run([godot, "--headless", "--path", str(game), "--import", "--quit"], capture_output=True, timeout=300, check=False)
    done = subprocess.run([godot, "--headless", "--path", str(game), "-s", "res://probe.gd"], capture_output=True, text=True,
                          encoding="utf-8", timeout=120, check=False)

    [line] = [x for x in done.stdout.splitlines() if x.startswith("PROBE ")]
    before, was_visible, after, default_visible = json.loads(line.removeprefix("PROBE "))
    assert before == 0 and was_visible is False and after >= 1 and default_visible is True


def test_a_state_removed_after_the_export_is_refused_naming_the_state(project: Kiripix) -> None:
    two_states(project)
    project.json("export", PROP)

    refused = project.json("decide", PROP, "source", "--decision",
                           json.dumps({"decision": "state_remove", "data": {"id": "toppled"}}), expect=1)

    assert [f["code"] for f in refused["findings"]] == ["export.id_frozen"] and "toppled" in refused["findings"][0]["message"]
