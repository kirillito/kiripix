"""Ticket 0342 (spec §9, ADR 0014): a room whose `normals` Stage has output exports the normal map cut for the Plate and each
Layer, a `CanvasTexture` `.tres` over each picture and its map in place of the plain texture, and `room.json`'s `normals`; all
in the Manifest. A room with `mode` `off` has `normals: null` and its scene as it was."""

import json
import os
import subprocess
from pathlib import Path
from typing import Any

import numpy as np
import pytest
from conftest import Kiripix
from PIL import Image
from test_export import ROOM, exportable_room, manifest, node, scene
from test_export_layers import layered_room, room_json

FOLDER = "game/kiripix/room/alley"
RES = "res://kiripix/room/alley"


def with_normals(project: Kiripix) -> Path:
    """The layered room, `normals` turned to `depth`, its depth accepted, and every Stage built again."""
    folder = layered_room(project)
    project.json("set", ROOM, "normals", "mode=depth")
    project.json("run", ROOM, expect=3)
    project.json("run", ROOM, "normals", "--rerun", expect=3)
    project.json("accept", ROOM, "normals", owner=True)
    project.json("run", ROOM)
    return folder


def pixels(path: Path) -> np.ndarray:
    with Image.open(path) as image:
        assert image.mode == "RGBA"
        return np.asarray(image, dtype=np.uint8)


def test_a_room_with_normals_exports_the_cut_maps_the_canvas_textures_and_lists_them_in_the_manifest(project: Kiripix) -> None:
    folder = with_normals(project)

    data = project.json("export", ROOM)["data"]

    game = project.cwd / FOLDER
    room = room_json(folder)
    assert room["schema_version"] == 15
    assert room["normals"] == {
        "plate": "normals/plate.png",
        "layers": {"lamp": "normals/layer.lamp.png", "crate": "normals/layer.crate.png"},
        "remainders": {}, "looks": {}, "loops": {}}
    wanted = [f"{RES}/normals/{name}.{ext}" for name in ("plate", "layer.lamp", "layer.crate") for ext in ("png", "tres")]
    assert set(wanted) <= set(data["written"])
    assert set(wanted) <= set(manifest(project)["files"])
    built = pixels(folder / "work" / "normals" / "normal.png")
    for name in ("plate", "layer.lamp", "layer.crate"):
        cut = pixels(game / "normals" / f"{name}.png")
        alpha = pixels(game / f"{name}.png")[..., 3]
        assert cut.shape == built.shape and ((cut[..., 3] > 0) == (alpha > 0)).all()
        assert (cut[alpha > 0] == built[alpha > 0]).all() and (cut[alpha == 0] == 0).all()
    assert (game / "normals" / "layer.lamp.tres").read_text("utf-8") == (
        "; generated by kiripix, do not edit\n"
        '[gd_resource type="CanvasTexture" load_steps=3 format=3]\n\n'
        f'[ext_resource type="Texture2D" path="{RES}/layer.lamp.png" id="colour"]\n\n'
        f'[ext_resource type="Texture2D" path="{RES}/normals/layer.lamp.png" id="normal"]\n\n'
        "[resource]\n"
        'diffuse_texture = ExtResource("colour")\n'
        'normal_texture = ExtResource("normal")\n')
    text = scene(project)
    assert f'[ext_resource type="CanvasTexture" path="{RES}/normals/plate.tres" id="plate"]' in text
    assert f'[ext_resource type="CanvasTexture" path="{RES}/normals/layer.lamp.tres" id="layer_lamp"]' in text
    assert 'texture = ExtResource("layer_lamp")' in node(text, "lamp", "Foreground")
    assert "load_steps=5 " in text


def test_an_export_of_the_same_room_again_writes_nothing(project: Kiripix) -> None:
    with_normals(project)
    project.json("export", ROOM)
    before = {p: p.read_bytes() for p in (project.cwd / FOLDER).rglob("*") if p.is_file()}

    again = project.json("export", ROOM)["data"]

    assert again["written"] == [] and again["unchanged"]
    assert before == {p: p.read_bytes() for p in (project.cwd / FOLDER).rglob("*") if p.is_file()}
    assert manifest(project)["counter"] == 1


def test_a_room_without_normals_has_null_and_no_normal_files_and_the_plain_scene(project: Kiripix) -> None:
    folder = exportable_room(project)

    data: dict[str, Any] = project.json("export", ROOM)["data"]

    assert room_json(folder)["normals"] is None
    assert not (project.cwd / FOLDER / "normals").exists()
    assert not any("normals" in res or res.endswith(".tres") for res in data["written"])
    text = scene(project)
    assert f'[ext_resource type="Texture2D" path="{RES}/plate.png" id="plate"]' in text and "CanvasTexture" not in text
    assert "normals" not in json.dumps(manifest(project)["files"])


def test_turning_normals_on_adds_files_and_no_id(project: Kiripix) -> None:
    with_normals(project)
    project.json("export", ROOM)

    ids = manifest(project)["ids"]

    assert ids["layers"] == ["plate", "crate", "lamp"] and "normals" not in json.dumps(ids)


PROBE = """extends SceneTree

func _init() -> void:
	var room: Node = load("res://kiripix/room/alley/alley.tscn").instantiate()
	for path in ["Plate", "Foreground/lamp", "Above/crate"]:
		var texture: Texture2D = room.get_node(path).texture
		var size := Vector2(0, 0)
		if texture is CanvasTexture and texture.normal_texture != null:
			size = texture.normal_texture.get_size()
		print("PROBE ", path, " ", texture is CanvasTexture, " ", size)
	room.free()
	quit()
"""


@pytest.mark.godot
def test_godot_loads_the_scene_and_the_plate_has_a_normal_texture(project: Kiripix) -> None:
    """Marked: real Godot 4.7 loads the scene; the Plate and each Layer show a CanvasTexture with a normal map."""
    with_normals(project)
    project.json("export", ROOM)
    game = project.cwd / "game"
    (game / "probe.gd").write_text(PROBE, "utf-8")
    godot = os.environ["KIRIPIX_GODOT"]

    subprocess.run([godot, "--headless", "--path", str(game), "--import", "--quit"], capture_output=True, timeout=300, check=False)
    done = subprocess.run([godot, "--headless", "--path", str(game), "-s", "res://probe.gd"], capture_output=True, text=True,
                          encoding="utf-8", timeout=120, check=False)

    lines = [x for x in done.stdout.splitlines() if x.startswith("PROBE ")]
    assert lines == ["PROBE Plate true (48.0, 32.0)", "PROBE Foreground/lamp true (48.0, 32.0)",
                     "PROBE Above/crate true (48.0, 32.0)"], done.stdout + done.stderr
