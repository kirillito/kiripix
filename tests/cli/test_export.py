GENERATED = "; generated by kiripix, do not edit"
SCENE = "game/kiripix/room/alley/alley.tscn"
PLATE = "game/kiripix/room/alley/plate.png"
MANIFEST = "game/kiripix/manifest/room.alley.json"
EXIT = {"target_room": "room.street", "target_exit": "exit.west"}


def set_target(project: Kiripix, path: str = "game", root: str = "res://kiripix") -> None:
    settings = project.cwd / "kiripix.toml"
    text = settings.read_text("utf-8").replace('# project = "C:/Workspace/my-game"   # the Godot project to export into',
                                                f'project = "{path}"')
    settings.write_text(text.replace('root = "res://kiripix"', f'root = "{root}"'), "utf-8")


def godot_project(project: Kiripix) -> Path:
    game = project.cwd / "game"
    game.mkdir()
    (game / "project.godot").write_text("config_version=5\n", "utf-8")
    return game


def exportable_room(project: Kiripix) -> Path:
    """A room with a wall in `solid` and a Spawn, a Godot project to export into, and every Stage built."""
    folder = walled_room(project)
    place(project, "spawn.main", "spawn")
    godot_project(project)
    set_target(project)
    project.json("run", ROOM)
    return folder


def manifest(project: Kiripix) -> dict[str, Any]:
    value: dict[str, Any] = json.loads((project.cwd / MANIFEST).read_text("utf-8"))
    return value


def scene(project: Kiripix) -> str:
    return (project.cwd / SCENE).read_text("utf-8")


def times(project: Kiripix) -> dict[str, int]:
    return {name: (project.cwd / name).stat().st_mtime_ns for name in (SCENE, PLATE, MANIFEST)}


def node(text: str, name: str, parent: str | None = None) -> str:
    """The section of one node in a scene, with its properties."""
    found = re.search(rf'^\[node name="{re.escape(name)}"[^\n]*\n(?:[^\[\n][^\n]*\n)*', text, re.MULTILINE)
    assert found, f"no node {name} in:\n{text}"
    if parent is not None:
        assert f'parent="{parent}"' in found.group(0)
    return found.group(0)


