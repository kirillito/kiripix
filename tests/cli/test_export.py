def test_an_export_stopped_while_writing_its_files_can_be_run_again(project: Kiripix) -> None:
    exportable_room(project)
    project.json("export", ROOM)
    res = "res://kiripix/room/alley/alley.tscn"
    place(project, "spawn.main", "spawn", at=(31, 16))
    project.json("run", ROOM)
    # What a stop leaves: the Manifest says what was being written, and the scene is still the old one.
    record = manifest(project)
    stopped = {**record, "files": {**record["files"], res: "0" * 64}, "replacing": {res: record["files"][res]},
               "counter": 2}
    (project.cwd / MANIFEST).write_text(json.dumps(stopped), "utf-8")

    data = project.json("export", ROOM)["data"]

    assert data["written"] == [res] and "position = Vector2(31, 16)" in scene(project)
    assert "replacing" not in manifest(project) and manifest(project)["counter"] == 3


