def test_the_stage_builds_engine_free_outputs_in_out(project: Kiripix) -> None:
    folder = exportable_room(project)

    assert stage_status(project, ROOM)["export"] == "done"
    room = json.loads((folder / "out" / "export" / "room.json").read_text("utf-8"))
    assert room["schema_version"] == 2 and room["size"] == [48, 32] and room["layers"] == []
    assert [marker["id"] for marker in room["markers"]] == ["spawn.main"]
    # The left wall, flooded into `solid` from the 48 x 32 Plate: 16 columns, all one rectangle.
    assert room["collision"]["solid"] == [[[0, 0], [16, 0], [16, 32], [0, 32]]]
    assert room["collision"]["pit"] == []
    # Walkable is x 22 to 42 and y 4 to 28 (see test_place), and the Spawn reaches all of it.
    assert room["navigation"]["outlines"] == [[[22, 4], [43, 4], [43, 29], [22, 29]]]
    with Image.open(folder / "out" / "export" / "plate.png") as image, \
            Image.open(folder / "work" / "palette" / "palette.png") as mapped:
        assert image.size == (48, 32) and image.tobytes() == mapped.tobytes()


