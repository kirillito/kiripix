def test_exporting_a_reached_room_writes_the_scene_the_png_and_the_manifest(project: Kiripix) -> None:
    exportable_room(project)

    data = project.json("export", ROOM)["data"]

    assert data["asset"] == ROOM and data["counter"] == 1 and data["unchanged"] == []
    assert sorted(data["written"]) == ["res://kiripix/room/alley/alley.tscn", "res://kiripix/room/alley/plate.png"]
    assert data["manifest"] == "res://kiripix/manifest/room.alley.json"
    text = scene(project)
    assert text.startswith(GENERATED + "\n[gd_scene ")
    assert '[ext_resource type="Texture2D" path="res://kiripix/room/alley/plate.png" id="plate"]' in text
    assert 'metadata/kiripix_id = "room.alley"' in node(text, "alley")
    plate = node(text, "Plate", ".")
    assert 'type="Sprite2D"' in plate and 'texture = ExtResource("plate")' in plate and "centered = false" in plate
    assert 'type="StaticBody2D"' in node(text, "solid", ".")
    assert "polygon = PackedVector2Array(0, 0, 16, 0, 16, 32, 0, 32)" in node(text, "polygon_0", "solid")
    assert 'type="NavigationRegion2D"' in node(text, "Navigation", ".")
    assert re.search(r"vertices = PackedVector2Array\(22, 4, 43, 4, 43, 29, 22, 29\)", text)
    assert "polygons = Array[PackedInt32Array]([PackedInt32Array(0, 1, 2, 3)])" in text
    spawn = node(text, "spawn-main", "Markers")
    assert 'type="Marker2D"' in spawn and "position = Vector2(30, 16)" in spawn
    assert 'metadata/kiripix_id = "spawn.main"' in spawn and 'metadata/kiripix_type = "spawn"' in spawn


