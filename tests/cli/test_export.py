def test_every_marker_type_is_exported_with_what_it_carries(project: Kiripix) -> None:
    walled_room(project)
    place(project, "spawn.main", "spawn")
    place(project, "exit.east", "exit", **EXIT)
    place(project, "lamp.one", "light", at=(30, 8), colour="#FF8000", radius=24, energy=0.5)
    place(project, "steam", "emitter", at=(32, 9), name="steam_pipe")
    place(project, "bin", "interactable", at=(33, 10))
    godot_project(project)
    set_target(project)
    project.json("run", ROOM)

    project.json("export", ROOM)

    text = scene(project)
    target = node(text, "exit-east", "Markers")
    assert 'metadata/target_room = "room.street"' in target and 'metadata/target_exit = "exit.west"' in target
    light = node(text, "lamp-one", "Lights")
    assert 'type="PointLight2D"' in light and "position = Vector2(30, 8)" in light
    assert "color = Color(1, 0.50196, 0, 1)" in light and "energy = 0.5" in light
    assert re.search(r'texture = SubResource\("light_0"\)', light)
    assert "width = 48" in text and "height = 48" in text
    emitter = node(text, "steam", "Emitters")
    assert 'type="GPUParticles2D"' in emitter and 'metadata/emitter = "steam_pipe"' in emitter
    assert 'metadata/kiripix_type = "interactable"' in node(text, "bin", "Markers")
    assert manifest(project)["ids"]["markers"] == sorted(["spawn.main", "exit.east", "lamp.one", "steam", "bin"])


