"""Writes `kiripix/commands/index.py`, the static index of the Commands (ticket 0277).

Adding a Command is two steps: declare it with `@command(...)`, then run `uv run python -m kiripix.commands.index_gen`.
`tests/cli/test_command_index.py` fails, naming the Command, when the index is out of date.

The index lets `kiripix` import only the module of the Command it runs. `MODULES` is the help order: the Commands
appear in the order they register when the modules are imported in that order (a module may import another).
"""

import importlib
import pkgutil
import sys
from pathlib import Path

import kiripix.commands as package
from kiripix.commands.registry import REGISTRY

MODULES = (
    "project", "show", "decisions", "sources", "clips", "checks", "export", "meta", "image_ops", "join_ops", "extend",
    "palette", "ramps", "clips_add", "area", "probes", "runners", "manifest", "timing", "loops",
)
INDEX_FILE = Path(__file__).with_name("index.py")

HEADER = '''"""The static index of the Commands: name, module and the words `--help` shows (ticket 0277).

GENERATED by `uv run python -m kiripix.commands.index_gen`; don't edit by hand. `tests/cli/test_command_index.py`
checks it against the real registry. It imports nothing, so reading it costs nothing.
"""

from typing import NamedTuple


class Entry(NamedTuple):
    module: str
    summary: str
    group_summary: str | None


INDEX: dict[str, Entry] = {
'''


def import_all() -> None:
    """Import every module of the package that declares Commands: the ordered ones first, then any new one."""
    names = [m.name for m in pkgutil.iter_modules(package.__path__)]
    ordered = [m for m in MODULES if m in names] + sorted(set(names) - set(MODULES))
    for name in ordered:
        importlib.import_module(f"kiripix.commands.{name}")


def source() -> str:
    """The text of `index.py` for the Commands as they are declared now."""
    import_all()
    lines = [f"    {cmd.name!r}: Entry({cmd.handler.__module__!r}, {cmd.summary!r}, {cmd.group_summary!r}),"
             for cmd in dict.values(REGISTRY)]  # registration order: what the help showed before the index
    return HEADER + "\n".join(lines) + "\n}\n"


if __name__ == "__main__":
    INDEX_FILE.write_text(source(), encoding="utf-8", newline="\n")
    sys.stdout.write(f"wrote {INDEX_FILE}\n")
