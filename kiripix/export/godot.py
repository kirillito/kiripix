"""Godot 4 text resources (spec §9): the scene of a room, from its `room.json`, and of a prop, from its `prop.json`.
Text only: no I/O here.

Marker IDs carry dots, which a node name can't, so a node is named with `-` in their place: no ID has one, so two IDs
never share a node. The ID itself goes into the node's metadata. A node's place is stable, because the game finds it by
its path: `Markers/spawn-main`, or a Mask's body by the Mask's name, as `solid`.
"""

from collections.abc import Iterable
from typing import Any

from kiripix.export.manifest import ExportedIds

GENERATED = "; generated by kiripix, do not edit"
PLATE = "Plate"
FOREGROUND = "Foreground"  # the y-sorted parent of the foreground Layers
ABOVE = "Above"  # the Layers that are always above the actors
ABOVE_Z = 100  # above any z_index an actor is likely to have; Godot draws a higher z_index over every lower one
# A pit stops walking but not a dash, so it has a body of its own, on a layer of its own: the game's Body collides with
# both layers when it walks, and drops the pit's from its collision mask while it dashes. `solid` always stops it.
COLLISION_LAYERS = {"solid": 1, "pit": 2}
_MARKER_PARENT = {"spawn": "Markers", "exit": "Markers", "interactable": "Markers", "light": "Lights",
                  "emitter": "Emitters", "area": "Markers"}
_MARKER_NODE = {"spawn": "Marker2D", "exit": "Marker2D", "interactable": "Marker2D", "light": "PointLight2D",
                "emitter": "GPUParticles2D", "area": "Area2D"}
AREA_SHAPE = "Shape"  # an area's CollisionShape2D: its place is stable, because the game finds it by its path


EXPORTED_MARKER_TYPES = frozenset(_MARKER_NODE)


def exported_markers(room: dict[str, Any]) -> list[dict[str, Any]]:
    """The Markers that become nodes. A y-sort line orders a foreground Layer and makes no node of its own."""
    return [marker for marker in room["markers"] if marker["type"] in EXPORTED_MARKER_TYPES]


def room_ids(room: dict[str, Any]) -> ExportedIds:
    """Every ID a room's export carries into the game: these are what the Manifest freezes."""
    layers = [PLATE.lower(), *sorted(str(layer["id"]) for layer in room["layers"])]
    return ExportedIds(markers=sorted(str(marker["id"]) for marker in exported_markers(room)), layers=layers,
                       masks=sorted(room["collision"]))


def _text(value: str) -> str:
    return '"' + value.replace("\\", "\\\\").replace('"', '\\"') + '"'


def _number(value: float) -> str:
    return f"{value:.5f}".rstrip("0").rstrip(".") if isinstance(value, float) else str(value)


def _vectors(points: Iterable[Iterable[int]]) -> str:
    return "PackedVector2Array(" + ", ".join(str(value) for point in points for value in point) + ")"


def _colour(hex_colour: str) -> str:
    channels = [int(hex_colour[i:i + 2], 16) / 255 for i in (1, 3, 5)]
    return "Color(" + ", ".join(_number(channel) for channel in channels) + ", 1)"


def _section(header: str, *properties: str) -> str:
    return "\n".join([header, *properties]) + "\n"


def _node(name: str, node_type: str, parent: str | None, *properties: str) -> str:
    place = f' parent="{parent}"' if parent is not None else ""
    return _section(f'[node name="{name}" type="{node_type}"{place}]', *properties)


def _node_name(marker_id: str) -> str:
    return marker_id.replace(".", "-")


def _light_resources(index: int, marker: dict[str, Any]) -> list[str]:
    """A soft round texture, since a PointLight2D shows nothing without one. Its size is the Marker's radius."""
    size = max(1, round(float(marker["radius"]) * 2))
    return [
        _section(f'[sub_resource type="Gradient" id="light_{index}_falloff"]',
                 "colors = PackedColorArray(1, 1, 1, 1, 1, 1, 1, 0)"),
        _section(f'[sub_resource type="GradientTexture2D" id="light_{index}"]',
                 f'gradient = SubResource("light_{index}_falloff")', f"width = {size}", f"height = {size}", "fill = 1",
                 "fill_from = Vector2(0.5, 0.5)", "fill_to = Vector2(1, 0.5)"),
    ]


def _area_size(marker: dict[str, Any]) -> tuple[int, int]:
    """An area's box in pixels: its corners are inclusive."""
    return int(marker["x2"]) - int(marker["x"]) + 1, int(marker["y2"]) - int(marker["y"]) + 1


def _area_shape_id(marker: dict[str, Any]) -> str:
    return f"area_{_node_name(str(marker['id']))}"


def _area_nodes(marker: dict[str, Any], parent: str) -> list[str]:
    """An `Area2D` at the centre of its box, with a `CollisionShape2D` of the box's size. It never touches physics: it
    monitors nothing, can't be monitored and sits on no collision layer. `walkable` and `cell` are only metadata."""
    width, height = _area_size(marker)
    name = _node_name(str(marker["id"]))
    centre = (int(marker["x"]) + width / 2, int(marker["y"]) + height / 2)
    properties = [f"position = Vector2({_number(centre[0])}, {_number(centre[1])})", "collision_layer = 0",
                  "collision_mask = 0", "monitoring = false", "monitorable = false",
                  f"metadata/kiripix_id = {_text(str(marker['id']))}", "metadata/kiripix_type = \"area\"",
                  f"metadata/walkable = {'true' if marker.get('walkable') else 'false'}"]
    if marker.get("cell") is not None:
        properties.append(f"metadata/cell = {int(marker['cell'])}")
    return [_node(name, "Area2D", parent, *properties),
            _node(AREA_SHAPE, "CollisionShape2D", f"{parent}/{name}", f'shape = SubResource("{_area_shape_id(marker)}")')]


def _marker_properties(marker: dict[str, Any], light: int | None) -> list[str]:
    properties = [f"position = Vector2({marker['x']}, {marker['y']})"]
    if light is not None:
        properties += [f"color = {_colour(str(marker['colour']))}", f"energy = {_number(float(marker['energy']))}",
                       f'texture = SubResource("light_{light}")']
    if marker["type"] == "emitter":
        properties.append("emitting = false")  # a stub: the game gives it its material
    properties += [f"metadata/kiripix_id = {_text(str(marker['id']))}",
                   f"metadata/kiripix_type = {_text(str(marker['type']))}"]
    if marker["type"] == "exit":
        properties += [f"metadata/target_room = {_text(str(marker['target_room']))}",
                       f"metadata/target_exit = {_text(str(marker['target_exit']))}"]
    if marker["type"] == "emitter":
        properties.append(f"metadata/emitter = {_text(str(marker['name']))}")
    return properties


def _foreground(layers: list[dict[str, Any]], folder: str) -> tuple[list[str], list[str]]:
    """The ext_resources and the nodes of the foreground Layers; nothing for a room with none.

    `Foreground` is y-sorted and holds each sorted Layer as a Sprite2D at its sort position, its offset cancelling the
    position so the pixels stay where they are. `Above` holds the "always above" Layers on a z_index over the actors."""
    resources = [f'[ext_resource type="Texture2D" path="{folder}/{layer["file"]}" id="layer_{layer["id"]}"]\n'
                 for layer in layers]
    sorted_layers = [layer for layer in layers if not layer["above"]]
    above = [layer for layer in layers if layer["above"]]
    nodes: list[str] = []
    if sorted_layers:
        nodes.append(_node(FOREGROUND, "Node2D", ".", "y_sort_enabled = true"))
        nodes += [_layer_sprite(layer, FOREGROUND, int(layer["y"])) for layer in sorted_layers]
    if above:
        nodes.append(_node(ABOVE, "Node2D", ".", f"z_index = {ABOVE_Z}"))
        nodes += [_layer_sprite(layer, ABOVE, 0) for layer in above]
    return resources, nodes


def _layer_sprite(layer: dict[str, Any], parent: str, y: int) -> str:
    """A Layer's Sprite2D at sort position `y`, its offset cancelling the position so the pixels stay where they are."""
    shift = [f"position = Vector2(0, {y})", f"offset = Vector2(0, {-y})"] if y else []
    return _node(_node_name(str(layer["id"])), "Sprite2D", parent, f'texture = ExtResource("layer_{layer["id"]}")',
                 "centered = false", *shift, f"metadata/kiripix_id = {_text(str(layer['id']))}")


def room_scene(room: dict[str, Any], name: str, plate_path: str) -> str:
    """The scene's text. `name` is the root node's, and `plate_path` the Plate's `res://` path."""
    layers = list(room["layers"])
    layer_resources, layer_nodes = _foreground(layers, plate_path.rsplit("/", 1)[0])
    # the root joins the y-sort only when a Layer sorts, so that the game's actors can sort with it (see the ticket)
    sorted_root = ["y_sort_enabled = true"] if any(not layer["above"] for layer in layers) else []
    markers = exported_markers(room)
    lights = [marker for marker in markers if marker["type"] == "light"]
    navigation = room["navigation"]
    resources = [resource for index, marker in enumerate(lights) for resource in _light_resources(index, marker)]
    resources += [_section(f'[sub_resource type="RectangleShape2D" id="{_area_shape_id(marker)}"]',
                           "size = Vector2({}, {})".format(*_area_size(marker)))
                  for marker in markers if marker["type"] == "area"]
    resources.append(_section(
        '[sub_resource type="NavigationPolygon" id="navigation"]',
        f"vertices = {_vectors(navigation['vertices'])}",
        "polygons = Array[PackedInt32Array]([" + ", ".join(
            "PackedInt32Array(" + ", ".join(str(index) for index in polygon) + ")" for polygon in navigation["polygons"]
        ) + "])",
        "outlines = Array[PackedVector2Array]([" + ", ".join(_vectors(ring) for ring in navigation["outlines"]) + "])",
    ))
    nodes = [
        _node(name, "Node2D", None, *sorted_root, f"metadata/kiripix_id = {_text(str(room['asset']))}"),
        _node(PLATE, "Sprite2D", ".", 'texture = ExtResource("plate")', "centered = false"),
        *layer_nodes,
    ]
    for mask, shapes in room["collision"].items():
        nodes.append(_node(mask, "StaticBody2D", ".", f"collision_layer = {COLLISION_LAYERS[mask]}", "collision_mask = 0"))
        nodes += [_node(f"polygon_{index}", "CollisionPolygon2D", mask, f"polygon = {_vectors(shape)}")
                  for index, shape in enumerate(shapes)]
    nodes.append(_node("Navigation", "NavigationRegion2D", ".", 'navigation_polygon = SubResource("navigation")'))
    for parent in ("Markers", "Lights", "Emitters"):
        nodes.append(_node(parent, "Node2D", "."))
        for marker in markers:
            if _MARKER_PARENT[marker["type"]] == parent and marker["type"] == "area":
                nodes += _area_nodes(marker, parent)
            elif _MARKER_PARENT[marker["type"]] == parent:
                light = lights.index(marker) if marker["type"] == "light" else None
                nodes.append(_node(_node_name(str(marker["id"])), _MARKER_NODE[marker["type"]], parent,
                                   *_marker_properties(marker, light)))
    header = f'[gd_scene load_steps={len(resources) + len(layer_resources) + 2} format=3]'
    plate = f'[ext_resource type="Texture2D" path="{plate_path}" id="plate"]\n'
    return GENERATED + "\n" + "\n".join([header + "\n", plate, *layer_resources, *resources, *nodes])


FOOTPRINT = "Footprint"  # a prop's body: its place is stable, because the game finds it by its path


def prop_ids(prop: dict[str, Any]) -> ExportedIds:
    """Every ID a prop's export carries into the game. The Footprint isn't frozen: the polygon can be emptied."""
    return ExportedIds(markers=[], layers=[], masks=[])


def prop_scene(prop: dict[str, Any], name: str, sprite_path: str) -> str:
    """The scene's text. The root sits at the prop's origin, so the game y-sorts it by its position, and its Sprite2D is
    drawn offset so that the origin pixel is the root's own place. `name` is the root node's."""
    ox, oy = prop["origin"]
    shapes = prop["collision"]
    nodes = [
        _node(name, "Node2D", None, f"metadata/kiripix_id = {_text(str(prop['asset']))}"),
        _node("Sprite", "Sprite2D", ".", 'texture = ExtResource("sprite")', "centered = false",
              f"offset = Vector2({-ox}, {-oy})"),
    ]
    if shapes:
        nodes.append(_node(FOOTPRINT, "StaticBody2D", ".", f"collision_layer = {COLLISION_LAYERS['solid']}",
                           "collision_mask = 0"))
        nodes += [_node(f"polygon_{index}", "CollisionPolygon2D", FOOTPRINT,
                        f"polygon = {_vectors([(x - ox, y - oy) for x, y in shape])}")
                  for index, shape in enumerate(shapes)]
    sprite = f'[ext_resource type="Texture2D" path="{sprite_path}" id="sprite"]\n'
    return GENERATED + "\n" + "\n".join(["[gd_scene load_steps=2 format=3]\n", sprite, *nodes])


# a character (spec §9): a CanvasTexture of the two atlases, a SpriteFrames over it, and a scene with an AnimatedSprite2D

SPRITE = "Sprite"  # a character's AnimatedSprite2D: its place is stable, because the game finds it by its path


def animation_name(clip: str, direction: str) -> str:
    return f"{clip}_{direction}"


def character_animations(character: dict[str, Any]) -> list[tuple[dict[str, Any], str, list[dict[str, Any]]]]:
    """Each animation as (clip, direction, frames): clips in `character.json`'s order, directions in the sheet's order."""
    return [(clip, direction, clip["directions"][direction]) for clip in character["clips"]
            for direction in character["directions"] if direction in clip["directions"]]


def character_ids(character: dict[str, Any]) -> ExportedIds:
    """Every ID a character's export carries into the game: its animation names. These are what the Manifest freezes."""
    names = sorted(animation_name(clip["name"], direction) for clip, direction, _ in character_animations(character))
    return ExportedIds(markers=[], layers=[], masks=[], clips=names)


def character_texture(colour_path: str, normal_path: str) -> str:
    """The CanvasTexture: the colour atlas as diffuse and the normal atlas as its normal map, filtered for pixel art."""
    return GENERATED + "\n" + "\n".join([
        "[gd_resource type=\"CanvasTexture\" load_steps=3 format=3]\n",
        f'[ext_resource type="Texture2D" path="{colour_path}" id="colour"]\n',
        f'[ext_resource type="Texture2D" path="{normal_path}" id="normal"]\n',
        _section("[resource]", 'diffuse_texture = ExtResource("colour")', 'normal_texture = ExtResource("normal")',
                 "texture_filter = 1"),
    ])


def character_frames(character: dict[str, Any], texture_path: str) -> str:
    """The SpriteFrames: one animation per clip and direction, each frame an AtlasTexture region of the CanvasTexture.
    Every frame lasts one frame time of its animation, whose speed is the clip's frame rate."""
    animations = character_animations(character)
    atlases: list[str] = []
    entries: list[str] = []
    for clip, direction, frames in animations:
        name = animation_name(clip["name"], direction)
        listed = []
        for frame in frames:
            ident = f"{name}_{frame['index']}"
            rect = frame["rect"]
            atlases.append(_section(f'[sub_resource type="AtlasTexture" id="{ident}"]', 'atlas = ExtResource("texture")',
                                    f"region = Rect2({rect['x']}, {rect['y']}, {rect['width']}, {rect['height']})"))
            listed.append(f'{{\n"duration": 1.0,\n"texture": SubResource("{ident}")\n}}')
        entries.append("{\n\"frames\": [" + ", ".join(listed) + "],\n"
                       f"\"loop\": {'true' if clip['loop'] else 'false'},\n\"name\": &\"{name}\",\n"
                       f"\"speed\": {int(clip['fps'])}.0\n}}")
    header = f'[gd_resource type="SpriteFrames" load_steps={len(atlases) + 2} format=3]'
    texture = f'[ext_resource type="CanvasTexture" path="{texture_path}" id="texture"]\n'
    return GENERATED + "\n" + "\n".join([
        header + "\n", texture, *atlases, _section("[resource]", "animations = [" + ", ".join(entries) + "]")])


def character_scene(character: dict[str, Any], name: str, frames_path: str, ramps_path: str | None = None,
                    parts: list[str] | None = None) -> str:
    """The scene's text. The root sits at the character's feet, so the game y-sorts it by its position, and the
    AnimatedSprite2D is drawn offset so that the pivot pixel of the cell is the root's own place. With `ramps_path` the root
    names `ramps.png` in `metadata/kiripix_ramps` and the part names in row order in `metadata/kiripix_parts`; the scene
    itself doesn't load it, since the game's shader does."""
    pivot = character["pivot"]
    first = character_animations(character)[0]
    ramps = ([f"metadata/kiripix_ramps = {_text(ramps_path)}",
              "metadata/kiripix_parts = PackedStringArray(" + ", ".join(_text(p) for p in parts or []) + ")"]
             if ramps_path is not None else [])
    nodes = [
        _node(name, "Node2D", None, f"metadata/kiripix_id = {_text(str(character['asset']))}", *ramps),
        _node(SPRITE, "AnimatedSprite2D", ".", 'sprite_frames = ExtResource("frames")',
              f'animation = &"{animation_name(first[0]["name"], first[1])}"', "centered = false",
              f"offset = Vector2({-pivot['x']}, {-pivot['y']})"),
    ]
    frames = f'[ext_resource type="SpriteFrames" path="{frames_path}" id="frames"]\n'
    return GENERATED + "\n" + "\n".join(["[gd_scene load_steps=2 format=3]\n", frames, *nodes])
