"""Godot 4 text resources (spec §9): the scene of a room, from its `room.json`, and of a prop, from its `prop.json`.
Text only: no I/O here.

Marker IDs carry dots, which a node name can't, so a node is named with `-` in their place: no ID has one, so two IDs
never share a node. The ID itself goes into the node's metadata. A node's place is stable, because the game finds it by
its path: `Markers/spawn-main`, or a Mask's body by the Mask's name, as `solid`.
"""

import re
from collections.abc import Iterable
from typing import Any

from kiripix.export.manifest import ExportedIds

GENERATED = "; generated by kiripix, do not edit"
PLATE = "Plate"
LOOKS = "Looks"  # the hidden Plate pieces of the room's Looks, one Sprite2D each
LOOPS = "Loops"  # the Plate pieces of the room's Loops, one Sprite2D each, drawn with the Plate (ticket 0190)
LOOP_UNSHADED = "loop_unshaded"  # the CanvasItemMaterial every Loop's Sprite2D shares: a Loop's frames aren't darkened by the room
LOOK_SOLIDS = "LookSolids"  # the Looks' own `solid` bodies, one StaticBody2D each, their shapes disabled
FOREGROUND = "Foreground"  # the y-sorted parent of the foreground Layers
ABOVE = "Above"  # the Layers that are always above the actors
ABOVE_Z = 100  # above any z_index an actor is likely to have; Godot draws a higher z_index over every lower one
# A pit stops walking but not a dash, so it has a body of its own, on a layer of its own: the game's Body collides with
# both layers when it walks, and drops the pit's from its collision mask while it dashes. `solid` always stops it.
COLLISION_LAYERS = {"solid": 1, "pit": 2}
_MARKER_PARENT = {"spawn": "Markers", "exit": "Markers", "interactable": "Markers", "light": "Lights",
                  "emitter": "Emitters", "area": "Markers"}
_MARKER_NODE = {"spawn": "Marker2D", "exit": "Marker2D", "interactable": "Marker2D", "light": "PointLight2D",
                "emitter": "GPUParticles2D", "area": "Area2D"}
AREA_SHAPE = "Shape"  # an area's CollisionShape2D: its place is stable, because the game finds it by its path


EXPORTED_MARKER_TYPES = frozenset(_MARKER_NODE)


def exported_markers(room: dict[str, Any]) -> list[dict[str, Any]]:
    """The Markers that become nodes. A y-sort line orders a foreground Layer and makes no node of its own."""
    return [marker for marker in room["markers"] if marker["type"] in EXPORTED_MARKER_TYPES]


def room_ids(room: dict[str, Any]) -> ExportedIds:
    """Every ID a room's export carries into the game: these are what the Manifest freezes."""
    layers = [PLATE.lower(), *sorted(str(layer["id"]) for layer in room["layers"])]
    return ExportedIds(markers=sorted(str(marker["id"]) for marker in exported_markers(room)), layers=layers,
                       masks=sorted(room["collision"]), looks=sorted(str(look["id"]) for look in room["looks"]),
                       loops=sorted(str(loop["id"]) for loop in room["loops"]))


def _text(value: str) -> str:
    return '"' + value.replace("\\", "\\\\").replace('"', '\\"') + '"'


def _number(value: float) -> str:
    return f"{value:.5f}".rstrip("0").rstrip(".") if isinstance(value, float) else str(value)


def _vectors(points: Iterable[Iterable[int]]) -> str:
    return "PackedVector2Array(" + ", ".join(str(value) for point in points for value in point) + ")"


def _colour(hex_colour: str) -> str:
    channels = [int(hex_colour[i:i + 2], 16) / 255 for i in (1, 3, 5)]
    return "Color(" + ", ".join(_number(channel) for channel in channels) + ", 1)"


def _section(header: str, *properties: str) -> str:
    return "\n".join([header, *properties]) + "\n"


def _node(name: str, node_type: str, parent: str | None, *properties: str) -> str:
    place = f' parent="{parent}"' if parent is not None else ""
    return _section(f'[node name="{name}" type="{node_type}"{place}]', *properties)


def _node_name(marker_id: str) -> str:
    return marker_id.replace(".", "-")


def _light_resources(index: int, marker: dict[str, Any]) -> list[str]:
    """A soft round texture, since a PointLight2D shows nothing without one. Its size is the Marker's radius."""
    size = max(1, round(float(marker["radius"]) * 2))
    return [
        _section(f'[sub_resource type="Gradient" id="light_{index}_falloff"]',
                 "colors = PackedColorArray(1, 1, 1, 1, 1, 1, 1, 0)"),
        _section(f'[sub_resource type="GradientTexture2D" id="light_{index}"]',
                 f'gradient = SubResource("light_{index}_falloff")', f"width = {size}", f"height = {size}", "fill = 1",
                 "fill_from = Vector2(0.5, 0.5)", "fill_to = Vector2(1, 0.5)"),
    ]


def _area_size(marker: dict[str, Any]) -> tuple[int, int]:
    """An area's box in pixels: its corners are inclusive."""
    return int(marker["x2"]) - int(marker["x"]) + 1, int(marker["y2"]) - int(marker["y"]) + 1


def _area_shape_ids(markers: list[dict[str, Any]]) -> dict[str, str]:
    """Each area's RectangleShape2D resource ID, from its ID rather than an index, so adding an area doesn't renumber the
    others. Godot allows only letters, digits and `_` in it, so `.` becomes `_`; two IDs that then meet (`a_b.c`, `a.b_c`)
    take `_2`, `_3` in the order of their IDs, so the suffix doesn't move."""
    ids: dict[str, str] = {}
    for marker_id in sorted(str(marker["id"]) for marker in markers if marker["type"] == "area"):
        base = "area_" + marker_id.replace(".", "_")
        ident, count = base, 1
        while ident in ids.values():
            count += 1
            ident = f"{base}_{count}"
        ids[marker_id] = ident
    return ids


def _area_nodes(marker: dict[str, Any], parent: str, shape_id: str) -> list[str]:
    """An `Area2D` at the centre of its box, with a `CollisionShape2D` of the box's size. It never touches physics: it
    monitors nothing, can't be monitored and sits on no collision layer. `walkable` and `cell` are only metadata."""
    width, height = _area_size(marker)
    name = _node_name(str(marker["id"]))
    centre = (int(marker["x"]) + width / 2, int(marker["y"]) + height / 2)
    properties = [f"position = Vector2({_number(centre[0])}, {_number(centre[1])})", "collision_layer = 0",
                  "collision_mask = 0", "monitoring = false", "monitorable = false",
                  f"metadata/kiripix_id = {_text(str(marker['id']))}", "metadata/kiripix_type = \"area\"",
                  f"metadata/walkable = {'true' if marker.get('walkable') else 'false'}"]
    if marker.get("cell") is not None:
        properties.append(f"metadata/cell = {int(marker['cell'])}")
    return [_node(name, "Area2D", parent, *properties),
            _node(AREA_SHAPE, "CollisionShape2D", f"{parent}/{name}", f'shape = SubResource("{shape_id}")')]


def _marker_properties(marker: dict[str, Any], light: int | None) -> list[str]:
    properties = [f"position = Vector2({marker['x']}, {marker['y']})"]
    if light is not None:
        properties += [f"color = {_colour(str(marker['colour']))}", f"energy = {_number(float(marker['energy']))}",
                       f'texture = SubResource("light_{light}")']
    if marker["type"] == "emitter":
        properties.append("emitting = false")  # a stub: the game gives it its material
    properties += [f"metadata/kiripix_id = {_text(str(marker['id']))}",
                   f"metadata/kiripix_type = {_text(str(marker['type']))}"]
    if marker["type"] == "exit":
        properties += [f"metadata/target_room = {_text(str(marker['target_room']))}",
                       f"metadata/target_exit = {_text(str(marker['target_exit']))}"]
    if marker["type"] == "emitter":
        properties.append(f"metadata/emitter = {_text(str(marker['name']))}")
        properties += _emitter_properties(marker)
    return properties


def _emitter_properties(marker: dict[str, Any]) -> list[str]:
    """An emitter's shape, direction and colours (ticket 0186), each only when set, so an old emitter is unchanged. Points
    are relative to the node. A box is its four corners clockwise from the top left, so the game reads every shape as one
    polygon; a point has a type and no points."""
    x, y = int(marker["x"]), int(marker["y"])
    properties: list[str] = []
    shape = marker.get("shape")
    if shape is not None:
        kind = str(shape["type"])
        properties.append(f"metadata/shape_type = {_text(kind)}")
        points: list[tuple[int, int]] = []
        if kind == "line":
            points = [(0, 0), (int(shape["x2"]) - x, int(shape["y2"]) - y)]
        elif kind == "box":
            right, bottom = int(shape["x2"]) - x, int(shape["y2"]) - y
            points = [(0, 0), (right, 0), (right, bottom), (0, bottom)]
        elif kind == "polygon":
            points = [(int(px) - x, int(py) - y) for px, py in shape["points"]]
        if points:
            properties.append(f"metadata/shape = {_vectors(points)}")
    direction = marker.get("direction")
    if direction is not None:
        properties.append(f"metadata/direction = Vector2({int(direction['x']) - x}, {int(direction['y']) - y})")
    colours = marker.get("colours")
    if colours:
        properties.append("metadata/colours = PackedColorArray(" + ", ".join(
            ", ".join(_number(int(colour[i:i + 2], 16) / 255) for i in (1, 3, 5)) + ", 1" for colour in colours) + ")")
    return properties


def _foreground(layers: list[dict[str, Any]], folder: str, loops: list[dict[str, Any]] | None = None,
                idents: dict[tuple[str, str | None], str] | None = None) -> tuple[list[str], list[str]]:
    """The ext_resources and the nodes of the foreground Layers; nothing for a room with none. A Layer a Loop moves shows
    the Loop's strip (its resource is the Loop's) instead of its own texture.

    `Foreground` is y-sorted and holds each sorted Layer as a Sprite2D at its sort position, its offset cancelling the
    position so the pixels stay where they are. `Above` holds the "always above" Layers on a z_index over the actors."""
    moving = _moving_layers(loops or [], idents or {})
    resources = [f'[ext_resource type="Texture2D" path="{folder}/{layer["file"]}" id="layer_{layer["id"]}"]\n'
                 for layer in layers if str(layer["id"]) not in moving]
    sorted_layers = [layer for layer in layers if not layer["above"]]
    above = [layer for layer in layers if layer["above"]]
    nodes: list[str] = []
    if sorted_layers:
        nodes.append(_node(FOREGROUND, "Node2D", ".", "y_sort_enabled = true"))
        nodes += [_layer_sprite(layer, FOREGROUND, int(layer["y"]), moving.get(str(layer["id"]))) for layer in sorted_layers]
    if above:
        nodes.append(_node(ABOVE, "Node2D", ".", f"z_index = {ABOVE_Z}"))
        nodes += [_layer_sprite(layer, ABOVE, 0, moving.get(str(layer["id"]))) for layer in above]
    return resources, nodes


def _moving_layers(loops: list[dict[str, Any]], idents: dict[tuple[str, str | None], str],
                   ) -> dict[str, tuple[dict[str, Any], str]]:
    """The Layers whose own Sprite2D shows a Loop's strip (`moves_layer`), each with the Loop and the strip's resource ID."""
    return {str(loop["layer"]): (loop, idents[(str(loop["id"]), str(loop["layer"]))])
            for loop in loops if loop.get("moves_layer") and loop["box"] is not None}


def _layer_sprite(layer: dict[str, Any], parent: str, y: int, moving: tuple[dict[str, Any], str] | None = None) -> str:
    """A Layer's Sprite2D at sort position `y`, its offset cancelling the position so the pixels stay where they are.
    When a Loop moves the Layer, the Sprite2D shows the Loop's strip instead: the position (the sort line) is unchanged,
    and the offset also carries the strip's place, so frame 0 draws the Layer's pixels where they were. The node keeps the
    Layer's ID and name, and the Loop's ID is `metadata/kiripix_loop`."""
    name = str(layer["id"])
    if moving is None:
        shift = [f"position = Vector2(0, {y})", f"offset = Vector2(0, {-y})"] if y else []
        return _node(_node_name(name), "Sprite2D", parent, f'texture = ExtResource("layer_{name}")', "centered = false",
                     *shift, f"metadata/kiripix_id = {_text(name)}")
    loop, ident = moving
    x0, y0 = int(loop["box"][0]), int(loop["box"][1])
    shift = [f"position = Vector2(0, {y})"] if y else []
    properties = [p for p in _loop_properties(loop) if not p.startswith("metadata/kiripix_id")]
    return _node(_node_name(name), "Sprite2D", parent, f'texture = ExtResource("{ident}")', "centered = false", *shift,
                 f"offset = Vector2({x0}, {y0 - y})", *properties, f"metadata/kiripix_id = {_text(name)}",
                 f"metadata/kiripix_loop = {_text(str(loop['id']))}")


def _idents(prefix: str, keys: Iterable[str]) -> dict[str, str]:
    """A resource ID for each key, from the key rather than an index, so adding one doesn't renumber the others. Godot
    allows only letters, digits and `_`, so anything else becomes `_`; keys that then meet take `_2`, `_3` in the order of
    the keys, so the suffix doesn't move."""
    ids: dict[str, str] = {}
    for key in sorted(keys):
        base = prefix + re.sub(r"\W", "_", key)
        ident, count = base, 1
        while ident in ids.values():
            count += 1
            ident = f"{base}_{count}"
        ids[key] = ident
    return ids


def _look_properties(look: dict[str, Any]) -> list[str]:
    """The metadata every node of a Look carries: its ID, which the game binds by, and its Condition only when it has one
    (a label for people and other Exporters, never evaluated by the game)."""
    properties = [f"metadata/kiripix_id = {_text(str(look['id']))}", 'metadata/kiripix_type = "look"']
    if look["condition"] is not None:
        properties.append(f"metadata/condition = {_text(str(look['condition']))}")
    return properties


def _look_pieces(looks: list[dict[str, Any]]) -> list[tuple[dict[str, Any], str | None, str]]:
    """Every picture of every Look as (Look, Layer or None for the Plate piece, file)."""
    pieces: list[tuple[dict[str, Any], str | None, str]] = []
    for look in looks:
        if look["file"] is not None:
            pieces.append((look, None, str(look["file"])))
        pieces += [(look, str(piece["layer"]), str(piece["file"])) for piece in look["pieces"]]
    return pieces


def _look_resources(looks: list[dict[str, Any]], folder: str) -> tuple[list[str], dict[tuple[str, str | None], str]]:
    pieces = _look_pieces(looks)
    keys = {(str(look["id"]), layer): f"{look['id']}:{layer}" if layer else str(look["id"]) for look, layer, _ in pieces}
    idents = _idents("look_", keys.values())
    named = {key: idents[text] for key, text in keys.items()}
    resources = [f'[ext_resource type="Texture2D" path="{folder}/{file}" id="{named[(str(look["id"]), layer)]}"]\n'
                 for look, layer, file in sorted(pieces, key=lambda p: named[(str(p[0]["id"]), p[1])])]
    return resources, named


def _look_sprite(look: dict[str, Any], parent: str, ident: str, x: int, y: int) -> str:
    """A hidden piece of a Look at (`x`, `y`) of its parent, where its pixels belong."""
    place = [f"position = Vector2({x}, {y})"] if x or y else []
    return _node(_node_name(str(look["id"])), "Sprite2D", parent, f'texture = ExtResource("{ident}")', "centered = false",
                 "visible = false", *place, *_look_properties(look))


def _look_nodes(looks: list[dict[str, Any]], layers: list[dict[str, Any]], idents: dict[tuple[str, str | None], str],
                ) -> tuple[list[str], list[str]]:
    """The nodes of the Looks: first the `Looks` and `LookSolids` parents with their children, then the pieces that sit
    under their Layer's node (a Layer's `Sprite2D` is positioned at its sort line, so its child's place is relative to it)."""
    bases = {str(layer["id"]): (ABOVE if layer["above"] else FOREGROUND, 0 if layer["above"] else int(layer["y"]))
             for layer in layers}
    own: list[str] = []
    pieces: list[str] = []
    solids: list[str] = []
    for look in looks:
        box = look["box"]
        if box is not None and look["file"] is not None:
            own.append(_look_sprite(look, LOOKS, idents[(str(look["id"]), None)], int(box[0]), int(box[1])))
        if box is not None:
            for piece in look["pieces"]:
                parent, line = bases[str(piece["layer"])]
                pieces.append(_look_sprite(look, f"{parent}/{_node_name(str(piece['layer']))}",
                                           idents[(str(look["id"]), str(piece["layer"]))], int(box[0]), int(box[1]) - line))
        if look["solid"] is not None:
            name = _node_name(str(look["id"]))
            solids.append(_node(name, "StaticBody2D", LOOK_SOLIDS, f"collision_layer = {COLLISION_LAYERS['solid']}",
                                "collision_mask = 0", *_look_properties(look)))
            solids += [_node(f"polygon_{index}", "CollisionPolygon2D", f"{LOOK_SOLIDS}/{name}", "disabled = true",
                             f"polygon = {_vectors(shape)}") for index, shape in enumerate(look["collision"]["solid"])]
    parents = [_node(LOOKS, "Node2D", "."), *own] if looks else []
    if any(look["solid"] is not None for look in looks):
        parents += [_node(LOOK_SOLIDS, "Node2D", "."), *solids]
    return parents, pieces


def _loop_properties(loop: dict[str, Any]) -> list[str]:
    """What every Sprite2D of a Loop carries: its frame layout and the metadata the game steps it by. The game sets `frame`
    from its own frame counter through `sequence` (a flat list of frame, ticks pairs) and `phase`; it never runs a clock here."""
    properties = [f"hframes = {int(loop['hframes'])}", f"vframes = {int(loop['vframes'])}", "frame = 0",
                  f'material = SubResource("{LOOP_UNSHADED}")',
                  f"metadata/kiripix_id = {_text(str(loop['id']))}", 'metadata/kiripix_type = "loop"',
                  "metadata/sequence = PackedInt32Array(" + ", ".join(str(int(value)) for value in loop["sequence"]) + ")",
                  f"metadata/phase = {int(loop['phase'])}"]
    if loop["light"] is not None:
        properties.append(f"metadata/light = {_text(str(loop['light']))}")
    return properties


def _loop_pieces(loops: list[dict[str, Any]]) -> list[tuple[dict[str, Any], str | None, str]]:
    """Every strip of every Loop that has a box, as (Loop, Layer or None for the Plate strip, file)."""
    pieces: list[tuple[dict[str, Any], str | None, str]] = []
    for loop in loops:
        if loop["box"] is None:
            continue
        if loop["file"] is not None:
            pieces.append((loop, None, str(loop["file"])))
        pieces += [(loop, str(piece["layer"]), str(piece["file"])) for piece in loop["pieces"]]
    return pieces


def _loop_resources(loops: list[dict[str, Any]], folder: str) -> tuple[list[str], dict[tuple[str, str | None], str]]:
    pieces = _loop_pieces(loops)
    keys = {(str(loop["id"]), layer): f"{loop['id']}:{layer}" if layer else str(loop["id"]) for loop, layer, _ in pieces}
    idents = _idents("loop_", keys.values())
    named = {key: idents[text] for key, text in keys.items()}
    resources = [f'[ext_resource type="Texture2D" path="{folder}/{file}" id="{named[(str(loop["id"]), layer)]}"]\n'
                 for loop, layer, file in sorted(pieces, key=lambda p: named[(str(p[0]["id"]), p[1])])]
    return resources, named


def _loop_sprite(loop: dict[str, Any], parent: str, ident: str, x: int, y: int) -> str:
    """A visible strip of a Loop at (`x`, `y`) of its parent, showing frame 0 where its pixels belong."""
    place = [f"position = Vector2({x}, {y})"] if x or y else []
    return _node(_node_name(str(loop["id"])), "Sprite2D", parent, f'texture = ExtResource("{ident}")', "centered = false",
                 *place, *_loop_properties(loop))


def _loop_nodes(loops: list[dict[str, Any]], layers: list[dict[str, Any]], idents: dict[tuple[str, str | None], str],
                ) -> tuple[list[str], list[str]]:
    """The nodes of the Loops: the `Loops` parent with a Sprite2D per Plate strip, then the strips that sit under their
    Layer's node, relative to its sort line as a Look's pieces are."""
    bases = {str(layer["id"]): (ABOVE if layer["above"] else FOREGROUND, 0 if layer["above"] else int(layer["y"]))
             for layer in layers}
    own: list[str] = []
    pieces: list[str] = []
    for loop in loops:
        box = loop["box"]
        if box is None:
            continue
        if loop["file"] is not None:
            own.append(_loop_sprite(loop, LOOPS, idents[(str(loop["id"]), None)], int(box[0]), int(box[1])))
        for piece in loop["pieces"]:
            if loop.get("moves_layer") and piece["layer"] == loop["layer"]:
                continue  # the Layer's own Sprite2D shows this strip
            parent, line = bases[str(piece["layer"])]
            pieces.append(_loop_sprite(loop, f"{parent}/{_node_name(str(piece['layer']))}",
                                       idents[(str(loop["id"]), str(piece["layer"]))], int(box[0]), int(box[1]) - line))
    return ([_node(LOOPS, "Node2D", "."), *own] if loops else []), pieces


def room_scene(room: dict[str, Any], name: str, plate_path: str, room_path: str) -> str:
    """The scene's text. `name` is the root node's, `plate_path` the Plate's `res://` path and `room_path` `room.json`'s,
    which the root's `metadata/kiripix_room` names so the game finds the Masks from the scene."""
    layers = list(room["layers"])
    folder = plate_path.rsplit("/", 1)[0]
    looks = list(room["looks"])
    look_resources, look_idents = _look_resources(looks, folder)
    look_parents, look_pieces = _look_nodes(looks, layers, look_idents)
    loops = list(room["loops"])
    loop_resources, loop_idents = _loop_resources(loops, folder)
    layer_resources, layer_nodes = _foreground(layers, folder, loops, loop_idents)
    loop_parents, loop_pieces = _loop_nodes(loops, layers, loop_idents)
    # the root joins the y-sort only when a Layer sorts, so that the game's actors can sort with it (see the ticket)
    sorted_root = ["y_sort_enabled = true"] if any(not layer["above"] for layer in layers) else []
    markers = exported_markers(room)
    lights = [marker for marker in markers if marker["type"] == "light"]
    navigation = room["navigation"]
    resources = [resource for index, marker in enumerate(lights) for resource in _light_resources(index, marker)]
    shape_ids = _area_shape_ids(markers)
    resources += [_section(f'[sub_resource type="RectangleShape2D" id="{shape_ids[str(marker['id'])]}"]',
                           "size = Vector2({}, {})".format(*_area_size(marker)))
                  for marker in markers if marker["type"] == "area"]
    if loops:
        resources.append(_section(f'[sub_resource type="CanvasItemMaterial" id="{LOOP_UNSHADED}"]', "light_mode = 1"))
    resources.append(_section(
        '[sub_resource type="NavigationPolygon" id="navigation"]',
        f"vertices = {_vectors(navigation['vertices'])}",
        "polygons = Array[PackedInt32Array]([" + ", ".join(
            "PackedInt32Array(" + ", ".join(str(index) for index in polygon) + ")" for polygon in navigation["polygons"]
        ) + "])",
        "outlines = Array[PackedVector2Array]([" + ", ".join(_vectors(ring) for ring in navigation["outlines"]) + "])",
    ))
    nodes = [
        _node(name, "Node2D", None, *sorted_root, f"metadata/kiripix_id = {_text(str(room['asset']))}",
              f"metadata/kiripix_room = {_text(room_path)}"),
        _node(PLATE, "Sprite2D", ".", 'texture = ExtResource("plate")', "centered = false"),
        *look_parents,
        *loop_parents,
        *layer_nodes,
        *look_pieces,
        *loop_pieces,
    ]
    for mask, shapes in room["collision"].items():
        nodes.append(_node(mask, "StaticBody2D", ".", f"collision_layer = {COLLISION_LAYERS[mask]}", "collision_mask = 0"))
        nodes += [_node(f"polygon_{index}", "CollisionPolygon2D", mask, f"polygon = {_vectors(shape)}")
                  for index, shape in enumerate(shapes)]
    nodes.append(_node("Navigation", "NavigationRegion2D", ".", 'navigation_polygon = SubResource("navigation")'))
    for parent in ("Markers", "Lights", "Emitters"):
        nodes.append(_node(parent, "Node2D", "."))
        for marker in markers:
            if _MARKER_PARENT[marker["type"]] == parent and marker["type"] == "area":
                nodes += _area_nodes(marker, parent, shape_ids[str(marker['id'])])
            elif _MARKER_PARENT[marker["type"]] == parent:
                light = lights.index(marker) if marker["type"] == "light" else None
                nodes.append(_node(_node_name(str(marker["id"])), _MARKER_NODE[marker["type"]], parent,
                                   *_marker_properties(marker, light)))
    header = f'[gd_scene load_steps={len(resources) + len(layer_resources) + len(look_resources) + len(loop_resources) + 2} format=3]'
    plate = f'[ext_resource type="Texture2D" path="{plate_path}" id="plate"]\n'
    return GENERATED + "\n" + "\n".join([header + "\n", plate, *layer_resources, *look_resources, *loop_resources, *resources, *nodes])


FOOTPRINT = "Footprint"  # a prop's body: its place is stable, because the game finds it by its path


def prop_ids(prop: dict[str, Any]) -> ExportedIds:
    """Every ID a prop's export carries into the game. The Footprint isn't frozen: the polygon can be emptied."""
    return ExportedIds(markers=[], layers=[], masks=[])


def prop_scene(prop: dict[str, Any], name: str, sprite_path: str) -> str:
    """The scene's text. The root sits at the prop's origin, so the game y-sorts it by its position, and its Sprite2D is
    drawn offset so that the origin pixel is the root's own place. `name` is the root node's."""
    ox, oy = prop["origin"]
    shapes = prop["collision"]
    nodes = [
        _node(name, "Node2D", None, f"metadata/kiripix_id = {_text(str(prop['asset']))}"),
        _node("Sprite", "Sprite2D", ".", 'texture = ExtResource("sprite")', "centered = false",
              f"offset = Vector2({-ox}, {-oy})"),
    ]
    if shapes:
        nodes.append(_node(FOOTPRINT, "StaticBody2D", ".", f"collision_layer = {COLLISION_LAYERS['solid']}",
                           "collision_mask = 0"))
        nodes += [_node(f"polygon_{index}", "CollisionPolygon2D", FOOTPRINT,
                        f"polygon = {_vectors([(x - ox, y - oy) for x, y in shape])}")
                  for index, shape in enumerate(shapes)]
    sprite = f'[ext_resource type="Texture2D" path="{sprite_path}" id="sprite"]\n'
    return GENERATED + "\n" + "\n".join(["[gd_scene load_steps=2 format=3]\n", sprite, *nodes])


# a character (spec §9): a CanvasTexture of the two atlases, a SpriteFrames over it, and a scene with an AnimatedSprite2D

SPRITE = "Sprite"  # a character's AnimatedSprite2D: its place is stable, because the game finds it by its path


def animation_name(clip: str, direction: str) -> str:
    return f"{clip}_{direction}"


def character_animations(character: dict[str, Any]) -> list[tuple[dict[str, Any], str, list[dict[str, Any]]]]:
    """Each animation as (clip, direction, frames): clips in `character.json`'s order, directions in the sheet's order."""
    return [(clip, direction, clip["directions"][direction]) for clip in character["clips"]
            for direction in character["directions"] if direction in clip["directions"]]


def character_ids(character: dict[str, Any]) -> ExportedIds:
    """Every ID a character's export carries into the game: its animation names. These are what the Manifest freezes."""
    names = sorted(animation_name(clip["name"], direction) for clip, direction, _ in character_animations(character))
    return ExportedIds(markers=[], layers=[], masks=[], clips=names)


def character_texture(colour_path: str, normal_path: str) -> str:
    """The CanvasTexture: the colour atlas as diffuse and the normal atlas as its normal map, filtered for pixel art."""
    return GENERATED + "\n" + "\n".join([
        "[gd_resource type=\"CanvasTexture\" load_steps=3 format=3]\n",
        f'[ext_resource type="Texture2D" path="{colour_path}" id="colour"]\n',
        f'[ext_resource type="Texture2D" path="{normal_path}" id="normal"]\n',
        _section("[resource]", 'diffuse_texture = ExtResource("colour")', 'normal_texture = ExtResource("normal")',
                 "texture_filter = 1"),
    ])


def character_frames(character: dict[str, Any], texture_path: str) -> str:
    """The SpriteFrames: one animation per clip and direction, each frame an AtlasTexture region of the CanvasTexture.
    Every frame lasts one frame time of its animation, whose speed is the clip's frame rate."""
    animations = character_animations(character)
    atlases: list[str] = []
    entries: list[str] = []
    for clip, direction, frames in animations:
        name = animation_name(clip["name"], direction)
        listed = []
        for frame in frames:
            ident = f"{name}_{frame['index']}"
            rect = frame["rect"]
            atlases.append(_section(f'[sub_resource type="AtlasTexture" id="{ident}"]', 'atlas = ExtResource("texture")',
                                    f"region = Rect2({rect['x']}, {rect['y']}, {rect['width']}, {rect['height']})"))
            listed.append(f'{{\n"duration": 1.0,\n"texture": SubResource("{ident}")\n}}')
        entries.append("{\n\"frames\": [" + ", ".join(listed) + "],\n"
                       f"\"loop\": {'true' if clip['loop'] else 'false'},\n\"name\": &\"{name}\",\n"
                       f"\"speed\": {int(clip['fps'])}.0\n}}")
    header = f'[gd_resource type="SpriteFrames" load_steps={len(atlases) + 2} format=3]'
    texture = f'[ext_resource type="CanvasTexture" path="{texture_path}" id="texture"]\n'
    return GENERATED + "\n" + "\n".join([
        header + "\n", texture, *atlases, _section("[resource]", "animations = [" + ", ".join(entries) + "]")])


def character_scene(character: dict[str, Any], name: str, frames_path: str, ramps_path: str | None = None,
                    parts: list[str] | None = None) -> str:
    """The scene's text. The root sits at the character's feet, so the game y-sorts it by its position, and the
    AnimatedSprite2D is drawn offset so that the pivot pixel of the cell is the root's own place. With `ramps_path` the root
    names `ramps.png` in `metadata/kiripix_ramps` and the part names in row order in `metadata/kiripix_parts`; the scene
    itself doesn't load it, since the game's shader does."""
    pivot = character["pivot"]
    first = character_animations(character)[0]
    ramps = ([f"metadata/kiripix_ramps = {_text(ramps_path)}",
              "metadata/kiripix_parts = PackedStringArray(" + ", ".join(_text(p) for p in parts or []) + ")"]
             if ramps_path is not None else [])
    nodes = [
        _node(name, "Node2D", None, f"metadata/kiripix_id = {_text(str(character['asset']))}", *ramps),
        _node(SPRITE, "AnimatedSprite2D", ".", 'sprite_frames = ExtResource("frames")',
              f'animation = &"{animation_name(first[0]["name"], first[1])}"', "centered = false",
              f"offset = Vector2({-pivot['x']}, {-pivot['y']})"),
    ]
    frames = f'[ext_resource type="SpriteFrames" path="{frames_path}" id="frames"]\n'
    return GENERATED + "\n" + "\n".join(["[gd_scene load_steps=2 format=3]\n", frames, *nodes])
